import { execFileSync } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
const { ADB_PATH: adb, ADB_SERIAL: serial, PYTHON_PATH: python } = process.env;
const width = Number(process.env.FALCON_LOGICAL_WIDTH);
const height = Number(process.env.FALCON_LOGICAL_HEIGHT);
const cropY = Number(process.env.FALCON_DRM_CROP_Y);
if (!adb || !serial || !python || width !== 960 || height !== 266 || !Number.isFinite(cropY)) throw new Error('Set ADB_PATH, ADB_SERIAL, PYTHON_PATH, FALCON_LOGICAL_WIDTH=960, FALCON_LOGICAL_HEIGHT=266 and the verified FALCON_DRM_CROP_Y for this acceptance profile.');
const output = resolve(process.argv[2] || 'artifacts/keyboard-demo/screen.png');
await mkdir(dirname(output), { recursive: true });
const shell = (command) => execFileSync(adb, ['-s', serial, 'shell', command], { encoding: 'utf8', timeout: 10000 }).replace(/\r/g, '');
const state = shell('cat /sys/kernel/debug/dri/0/state');
const plane = state.split(/(?=plane\[)/).find((part) => part.includes('allocated by = miniapp') && part.includes('format=AR24') && part.includes('size=480x960'));
const fb = plane && /\bfb=(\d+)/.exec(plane);
if (!fb) throw new Error('Current miniapp AR24 framebuffer not found; do not reuse an old framebuffer id.');
shell(`/tmp/falcon-component-device-probe capture /dev/dri/card0 ${fb[1]} /tmp/falcon-keyboard-frame.raw`);
const raw = resolve('artifacts/keyboard-demo/current-frame.raw');
execFileSync(adb, ['-s', serial, 'pull', '/tmp/falcon-keyboard-frame.raw', raw], { stdio: 'pipe', timeout: 10000 });
execFileSync(python, ['-c', 'from PIL import Image; from pathlib import Path; import sys; Image.frombytes("RGBA",(480,960),Path(sys.argv[1]).read_bytes(),"raw","BGRA",1920).rotate(270,expand=True).crop((0,int(sys.argv[3]),960,int(sys.argv[3])+266)).convert("RGB").save(sys.argv[2])', raw, output, String(cropY)], { stdio: 'inherit', windowsHide: true });
console.log('Captured current DRM framebuffer: ' + output);
