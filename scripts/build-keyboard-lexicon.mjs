import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { toT9 } from '../packages/keyboard/src/pinyin.js';

const base = new URL('../packages/keyboard/data/', import.meta.url);
const source = await readFile(new URL('pinyin_simp.dict.yaml', base));
const lines = source.toString('utf8').split(/\r?\n/);
const entries = lines.filter((line) => /^[^#\s].*\t[a-zü ]+\t\d+$/.test(line)).map((line) => {
  const [word, pronunciation, weight] = line.split('\t');
  return `${word}\t${pronunciation.replace(/ü/g, 'v')}\t${weight}`;
});
if (entries.length < 60000) throw new Error('Incomplete upstream dictionary');
const records = entries.map((line) => {
  const [word, pinyin, weight] = line.split('\t');
  const code = pinyin.replace(/ /g, '');
  return [word, pinyin, Number(weight), code, toT9(code)];
});
const sorted = (column) => records.map((row, i) => i).sort((a, b) => records[a][column] < records[b][column] ? -1 : records[a][column] > records[b][column] ? 1 : records[b][2] - records[a][2]);
const indexed = { records, qwerty: sorted(3), t9: sorted(4) };
await writeFile(new URL('lexicon.js', base), `// Generated by scripts/build-keyboard-lexicon.mjs; data is Apache-2.0.\nexport default ${JSON.stringify(JSON.stringify(indexed))};\n`);
await writeFile(new URL('provenance.json', base), JSON.stringify({
  repository: 'https://github.com/rime/rime-pinyin-simp',
  commit: '0c6861ef7420ee780270ca6d993d18d4101049d0',
  file: 'pinyin_simp.dict.yaml', license: 'Apache-2.0', entries: entries.length,
  sha256: createHash('sha256').update(source).digest('hex'),
  transformation: 'Retain all records; replace ü with v; preserve word, syllables and weight; precompute sorted pinyin/T9 indexes. No Rime code included.',
}, null, 2) + '\n');
console.log(`Generated ${entries.length} dictionary records.`);
